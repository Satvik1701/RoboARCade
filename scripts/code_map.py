"""Writes docs/code/CODE_MAP.md.

Every tracked file that is not data (code, prompts, guides, READMEs, task definitions and scenes, config), grouped by
directory, with its size, the first paragraph of its docstring or header comment, and the in-repo modules it imports.
The docs overview's size table uses the same enumeration. Run from the repo root: .venv/bin/python scripts/code_map.py"""
import ast
import itertools
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/code/CODE_MAP.md"
FOLDERS = (".", "core", "interfaces", "dashboard", "tasks", "scripts", ".github")
CODE_EXT = (".py", ".js", ".html", ".css", ".sh")
DATA_EXT = (".obj", ".stl", ".png", ".jpg", ".npz", ".npy", ".mp4", ".lock")
DATA_NAMES = ("manifest.json",)
DESCRIBED = {
    "task.json": "The task: instruction, robots, cameras, objects, randomization and the success tree.",
    "scene.xml": "The task's MuJoCo scene.",
    "manifest.json": "What the interface needs from the simulator: arm count, the browser page, RGB-D snapshots.",
    "pyproject.toml": "Package metadata and dependencies.",
    ".mcp.json": "The MCP server the agent loads.",
    ".gitignore": "Files git leaves untracked.",
    "set_env.sh": "Environment for every run: paths, rendering backend, the Python environment.",
}


def is_data(rel):
    parts = rel.parts
    if rel.suffix in DATA_EXT or "vendor" in parts or "fixtures" in parts:
        return True
    return rel.name in DATA_NAMES and parts[0] == "tasks"


def code_files(folder):
    def git_files(*flags):
        return set(filter(None, subprocess.run(["git", "ls-files", "-z", *flags, "--", folder], cwd=ROOT,
                                               capture_output=True, text=True, check=True).stdout.split("\0")))
    force_added = git_files("-ci", "--exclude-standard")
    tracked = git_files() - force_added
    out = []
    for name in sorted(tracked):
        rel = Path(name)
        if (folder == ".") != (len(rel.parts) == 1) or is_data(rel):
            continue
        p = ROOT / rel
        if p.is_file() and not p.is_symlink():
            out.append(p)
    return sorted(out)


def count_lines(path):
    return sum(1 for _ in open(path, errors="ignore"))


def summary(path, src):
    doc = ""
    if path.name in DESCRIBED and (path.name != "manifest.json" or "interfaces" in path.parts):
        doc = DESCRIBED[path.name]
    elif path.name == "__init__.py" and not src.strip():
        doc = "Package marker (empty)."
    elif path.suffix == ".html":
        m = re.search(r"<!--(.*?)-->", src[:2000], re.S)
        doc = "\n".join(line.strip() for line in m.group(1).splitlines()) if m else ""
    elif path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(src)) or ""
        except SyntaxError:
            pass
    elif path.suffix == ".js":
        m = re.match(r"\s*/\*(.*?)\*/", src, re.S)
        lines = m.group(1).splitlines() if m else [line[2:] for line in itertools.takewhile(lambda l: l.startswith("//"), src.splitlines())]
        doc = "\n".join(line.strip() for line in lines)
    elif path.suffix == ".md":
        doc = re.sub(r"^#[^\n]*\n+", "", src.lstrip())
    elif path.suffix == ".txt":
        doc = src
    elif path.suffix in (".sh", ".yaml", ".yml"):
        head = []
        for line in src.splitlines()[1 if src.startswith("#!") else 0:]:
            if not line.startswith("#"):
                break
            head.append(line.lstrip("# ").rstrip())
        doc = "\n".join(head)
    first = re.split(r"\n\s*\n", doc.strip())[0].replace("\n", " ") if doc else ""
    first = first.replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")
    parts = first.split("`")
    return "`".join(t if i % 2 else t.replace("*", "\\*").replace("_", "\\_") for i, t in enumerate(parts))


def imports(src, names):
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return []
    out = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.ImportFrom) and n.module:
            out |= {m for m in [n.module, *(n.module + "." + a.name for a in n.names)] if m in names}
        elif isinstance(n, ast.Import):
            out |= {a.name for a in n.names if a.name in names}
    return sorted(out)


def module_name(path):
    return str(path.relative_to(ROOT))[:-3].replace("/", ".").removesuffix(".__init__")


def label(folder):
    return "repository root" if folder == "." else f"`{folder}/`"


def main():
    files = {folder: code_files(folder) for folder in FOLDERS}
    names = {module_name(p) for f in ("core", "interfaces", "dashboard", "tasks") for p in files[f] if p.suffix == ".py"}
    out = ["# Code map", "",
           "Generated by `scripts/code_map.py`: every tracked file that is not data (code, prompts, guides, READMEs, task "
           "definitions and scenes, config), grouped by directory, with its size, the first paragraph of its docstring or "
           "header comment, and the in-repo modules it imports. Left out as data: meshes, images, arrays, recorded fixture "
           "states, each task's asset hash list (manifest.json), vendored third-party code and uv.lock; docs/ is this site. "
           "Python files without a docstring are marked **undocumented**. The folder totals are the overview's numbers.", "",
           "| Folder | Files | Lines |", "|---|---:|---:|"]
    totals = {folder: (len(paths), sum(count_lines(p) for p in paths)) for folder, paths in files.items()}
    out += [f"| {label(folder)} | {n} | {lines:,} |" for folder, (n, lines) in totals.items()]
    out.append(f"| total | {sum(n for n, _ in totals.values())} | {sum(l for _, l in totals.values()):,} |")
    for folder, paths in files.items():
        out += ["", f"## {label(folder)} ({totals[folder][0]} files, {totals[folder][1]:,} lines)"]
        groups = {}
        for p in paths:
            groups.setdefault(str(p.parent.relative_to(ROOT)), []).append(p)
        for group, members in groups.items():
            out += ["", f"### {label(group)}", "", "| File | Lines | What it is | Imports |", "|---|---:|---|---|"]
            for p in sorted(members, key=lambda q: -count_lines(q)):
                src = p.read_text(errors="ignore")
                what = summary(p, src) or ("**undocumented**" if p.suffix == ".py" else "")
                deps = ", ".join(f"`{d.removeprefix('core.')}`" for d in imports(src, names)) if p.suffix == ".py" else ""
                out.append(f"| `{p.name}` | {count_lines(p)} | {what} | {deps} |")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT.relative_to(ROOT), ", ".join(f"{f} {n} files {l:,} lines" for f, (n, l) in totals.items()))


if __name__ == "__main__":
    main()
